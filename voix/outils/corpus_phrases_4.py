def generer() -> list[Cas]:
    r = random.Random(GRAINE)
    cas = [Cas(p, i, dict(params), "refus" if i == "refus" else "compris") for p, i, params in PHRASES]
    for c in cas:  # bruit de transcription : casse, ponctuation
        if r.random() < 0.4:
            c.phrase = c.phrase[0].upper() + c.phrase[1:] + r.choice([".", " ?", " !"])
    return cas


