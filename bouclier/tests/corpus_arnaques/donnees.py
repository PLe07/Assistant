"""Le corpus principal : des messages fictifs, écrits comme ceux qui circulent en France (§11.1).

Chaque entrée : (identifiant, canal, famille, contenu).
- SMS : le texte tel que l'iPhone le partage (sans expéditeur).
- Mail : un dictionnaire (expéditeur, sujet, corps avec {0}, {1}… pour les liens, liens (texte affiché, adresse réelle),
  résultats d'authentification, Reply-To, désinscription, encodage).
Aucun nom, numéro ou adresse réels : tout est inventé (les numéros en 01 84, 09 70… sont des exemples).
"""

from __future__ import annotations

from typing import Any

Mail = dict[str, Any]


def mail(
    de: str,
    sujet: str,
    corps: str,
    liens: list[tuple[str, str]] | None = None,
    *,
    auth: str = "none",
    reply_to: str | None = None,
    desinscription: bool = False,
    encodage: str = "utf-8",
    html: bool = True,
) -> Mail:
    return {
        "de": de,
        "sujet": sujet,
        "corps": corps,
        "liens": liens or [],
        "auth": auth,
        "reply_to": reply_to,
        "desinscription": desinscription,
        "encodage": encodage,
        "html": html,
    }


# Authentification d'un vrai expéditeur : SPF, DKIM et DMARC passent pour son domaine.
def ok(domaine: str) -> str:
    return f"pass:{domaine}"


